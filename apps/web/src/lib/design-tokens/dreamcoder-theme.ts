/**
 * Builds Drenyra's theme primitives from the Dreamcoder palette
 * (dreamcoder-dots/DreamcoderThemes/dreamcoder/tokens.json), the single
 * source of truth for the light and dark themes.
 *
 * Output: `--dc-<role>` custom properties for dark (`:root, .force-dark`) and
 * light (`.light`). Every other theme variable in index.css aliases these.
 * Regenerate with `bun run tokens:dreamcoder <path-to-tokens.json>`.
 */

type ModeName = "dark" | "light";
type ModeTokens = Record<string, unknown> & {
	aliases?: Record<string, unknown>;
};
export interface DreamcoderTokens {
	modes: Partial<Record<ModeName, ModeTokens>> & Record<string, unknown>;
}

/** Semantic role -> token key per mode (`aliases.x` reads the mode's aliases). */
export const DREAMCODER_ROLES: Record<string, Record<ModeName, string>> = {
	canvas: { dark: "bg", light: "bg" },
	soft: { dark: "bg_soft", light: "bg_soft" },
	// Cards and popovers: the panel layer in dark, the lightest layer in light.
	raised: { dark: "surface1", light: "surface0" },
	sunken: { dark: "surface2", light: "surface1" },
	strong: { dark: "surface3", light: "surface2" },
	hairline: { dark: "aliases.border_medium", light: "surface2" },
	"hairline-subtle": { dark: "aliases.border_subtle", light: "surface1" },
	"border-ui": { dark: "border_ui", light: "border_ui" },
	"border-hi": { dark: "border_hi", light: "border_hi" },
	text: { dark: "text", light: "text" },
	"text-heading": { dark: "text_heading", light: "text_heading" },
	"text-secondary": { dark: "muted", light: "muted" },
	"text-muted": { dark: "subtle", light: "subtle" },
	"text-disabled": { dark: "disabled", light: "disabled" },
	accent: { dark: "accent", light: "accent" },
	"accent-2": { dark: "accent_2", light: "accent_2" },
	"on-accent": { dark: "on_accent", light: "on_accent" },
	link: { dark: "link", light: "link" },
	"link-hover": { dark: "link_hover", light: "link_hover" },
	focus: { dark: "focus", light: "focus" },
	success: { dark: "success", light: "success" },
	warning: { dark: "warning", light: "warning" },
	error: { dark: "error", light: "error" },
	"on-error": { dark: "on_error", light: "on_error" },
	info: { dark: "info", light: "info" },
	"selection-bg": { dark: "selection_bg", light: "selection_bg" },
	"selection-fg": { dark: "selection_fg", light: "selection_fg" },
	hover: { dark: "hover", light: "hover" },
	pressed: { dark: "pressed", light: "pressed" },
	overlay: { dark: "overlay", light: "overlay" },
	scrim: { dark: "scrim", light: "scrim" },
};

/** Roles also emitted as `R G B` triplets for `rgb(var(--dc-x-rgb) / a)` usage. */
const RGB_ROLES = ["accent", "success", "warning", "error", "info"] as const;

function readToken(mode: ModeTokens, modeName: ModeName, path: string): string {
	const value = path.startsWith("aliases.")
		? mode.aliases?.[path.slice("aliases.".length)]
		: mode[path];
	if (typeof value !== "string" || value.length === 0) {
		throw new Error(`Dreamcoder tokens: missing "${modeName}.${path}"`);
	}
	return value;
}

function hexToRgbTriplet(hex: string): string {
	const match = /^#([0-9a-f]{6})$/i.exec(hex);
	if (!match?.[1])
		throw new Error(`Dreamcoder tokens: expected #rrggbb, got "${hex}"`);
	const int = Number.parseInt(match[1], 16);
	return `${(int >> 16) & 255} ${(int >> 8) & 255} ${int & 255}`;
}

function modeBlock(tokens: DreamcoderTokens, modeName: ModeName): string[] {
	const mode = tokens.modes[modeName];
	if (!mode) throw new Error(`Dreamcoder tokens: missing mode "${modeName}"`);

	const values = Object.fromEntries(
		Object.entries(DREAMCODER_ROLES).map(([role, keys]) => [
			role,
			readToken(mode, modeName, keys[modeName]),
		]),
	);
	return [
		...Object.entries(values).map(
			([role, value]) => `  --dc-${role}: ${value};`,
		),
		...RGB_ROLES.map(
			(role) =>
				`  --dc-${role}-rgb: ${hexToRgbTriplet(values[role] as string)};`,
		),
	];
}

export function buildDreamcoderThemeCss(
	tokens: DreamcoderTokens,
	source: string,
): string {
	return [
		"/* GENERATED by scripts/generate-dreamcoder-theme.ts — do not edit by hand.",
		` * Source: ${source}`,
		" * Dark is the default (and .force-dark for auth screens); .light overrides it. */",
		":root,",
		".force-dark {",
		"  color-scheme: dark;",
		...modeBlock(tokens, "dark"),
		"}",
		"",
		".light {",
		"  color-scheme: light;",
		...modeBlock(tokens, "light"),
		"}",
		"",
	].join("\n");
}
